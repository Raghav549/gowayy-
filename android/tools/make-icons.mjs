#!/usr/bin/env node
/**
 * Builds the Android launcher icon from the gowayy wordmark — the same
 * lowercase "gowayy" set in Bricolage Grotesque Bold with -0.055em tracking
 * that the web app uses (src/components/Logo.tsx, dark variant), on the brand
 * purple gradient.
 *
 * The letters are converted to vector outlines, so the adaptive icon stays
 * sharp at every size and needs no font on the phone. Outputs (committed):
 *   app/src/main/res/drawable/ic_launcher_{foreground,background,monochrome}.xml
 *   app/src/main/res/mipmap-anydpi-v26/ic_launcher{,_round}.xml
 *   app/src/main/res/mipmap-<dpi>/ic_launcher{,_round}.png   (Android 7.x)
 *   icon-512.png                                              (store / preview)
 *
 * Run from the repo root after changing the logo:
 *   npm i --no-save opentype.js@2 @fontsource/bricolage-grotesque
 *   node android/tools/make-icons.mjs
 */
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const opentype = require("opentype.js");
const sharp = require("sharp");

const here = dirname(fileURLToPath(import.meta.url));
const androidDir = join(here, "..");
const res = join(androidDir, "app/src/main/res");
const fontFile = require.resolve("@fontsource/bricolage-grotesque/files/bricolage-grotesque-latin-700-normal.woff");

// Brand palette (src/app/globals.css + LogoMark).
const BG = [["0", "#A07BFF"], ["0.55", "#7C3AED"], ["1", "#4C1D95"]];
const INK = "#FFFFFF"; // "gowa" on the dark variant
const YY = [["0", "#DAC9FF"], ["1", "#F0ABFC"]]; // brand-200 → fuchsia-300

// ---------- lay out the wordmark ----------
const font = opentype.parse(readFileSync(fontFile).buffer);
const SIZE = 100; // working size, scaled to fit below
const tracking = -0.055 * SIZE;
function layout(text, x0) {
  const glyphs = [...text].map((ch) => font.charToGlyph(ch)); // plain Latin: no shaping needed
  const scale = SIZE / font.unitsPerEm;
  let x = x0;
  const paths = [];
  glyphs.forEach((g, i) => {
    paths.push(g.getPath(x, 0, SIZE));
    x += g.advanceWidth * scale + tracking;
    if (glyphs[i + 1]) x += font.getKerningValue(g, glyphs[i + 1]) * scale;
  });
  return { paths, end: x };
}
const gowa = layout("gowa", 0);
const yy = layout("yy", gowa.end);

const box = { x1: Infinity, y1: Infinity, x2: -Infinity, y2: -Infinity };
for (const p of [...gowa.paths, ...yy.paths]) {
  const b = p.getBoundingBox();
  box.x1 = Math.min(box.x1, b.x1); box.y1 = Math.min(box.y1, b.y1);
  box.x2 = Math.max(box.x2, b.x2); box.y2 = Math.max(box.y2, b.y2);
}

/** Path data of a group, scaled so the word spans `width` and is centred on (cx, cy). */
function placed(group, width, cx, cy) {
  const k = width / (box.x2 - box.x1);
  const ox = cx - ((box.x1 + box.x2) / 2) * k;
  const oy = cy - ((box.y1 + box.y2) / 2) * k;
  const X = (v) => (ox + v * k).toFixed(2);
  const Y = (v) => (oy + v * k).toFixed(2);
  return group.paths
    .flatMap((p) => p.commands)
    .map((c) => {
      switch (c.type) {
        case "M": case "L": return `${c.type}${X(c.x)},${Y(c.y)}`;
        case "Q": return `Q${X(c.x1)},${Y(c.y1)} ${X(c.x)},${Y(c.y)}`;
        case "C": return `C${X(c.x1)},${Y(c.y1)} ${X(c.x2)},${Y(c.y2)} ${X(c.x)},${Y(c.y)}`;
        default: return "Z";
      }
    })
    .join("");
}
const wordBox = (width) => ({ w: width, h: ((box.y2 - box.y1) * width) / (box.x2 - box.x1) });

// ---------- adaptive icon (108 × 108 dp, 66 dp safe circle) ----------
const W = 64; // word width in dp — its corners stay inside the safe circle
{
  const { w, h } = wordBox(W);
  if (Math.hypot(w, h) > 66) throw new Error(`wordmark ${w}×${h} does not fit the safe zone`);
}
const fgGowa = placed(gowa, W, 54, 54);
const fgYy = placed(yy, W, 54, 54);
const { w: ww, h: wh } = wordBox(W);
// Horizontal extent of "yy" in dp, for its gradient.
const yyStart = Math.min(...yy.paths.map((p) => p.getBoundingBox().x1));
const yx1 = 54 - ww / 2 + ((yyStart - box.x1) * ww) / (box.x2 - box.x1);
const yx2 = 54 + ww / 2;

const xml = (body) => `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by android/tools/make-icons.mjs — do not edit by hand. -->\n${body}\n`;
const vec = (inner) =>
  xml(`<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
${inner}
</vector>`);
const stops = (list) => list.map(([o, c]) => `                <item android:offset="${o}" android:color="#FF${c.slice(1)}" />`).join("\n");

const background = vec(`    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="12" android:startY="0" android:endX="96" android:endY="108">
${stops(BG)}
            </gradient>
        </aapt:attr>
    </path>
    <!-- soft orchid glow, top right -->
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="88" android:centerY="16" android:gradientRadius="58">
                <item android:offset="0" android:color="#66F5C2FF" />
                <item android:offset="1" android:color="#00F5C2FF" />
            </gradient>
        </aapt:attr>
    </path>
    <!-- deep shade, bottom left -->
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="10" android:centerY="104" android:gradientRadius="62">
                <item android:offset="0" android:color="#552E1065" />
                <item android:offset="1" android:color="#002E1065" />
            </gradient>
        </aapt:attr>
    </path>`);

const foreground = vec(`    <path android:fillColor="${INK}" android:pathData="${fgGowa}" />
    <path android:pathData="${fgYy}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="${yx1.toFixed(2)}" android:startY="${(54 - wh / 2).toFixed(2)}" android:endX="${yx2.toFixed(2)}" android:endY="${(54 + wh / 2).toFixed(2)}">
${stops(YY)}
            </gradient>
        </aapt:attr>
    </path>`);

// Android 13+ themed icons: the system tints this single-colour shape.
const monochrome = vec(`    <path android:fillColor="#FFFFFFFF" android:pathData="${fgGowa}${fgYy}" />`);

const adaptive = xml(`<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>`);

const write = (p, s) => { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, s); };
write(join(res, "drawable/ic_launcher_background.xml"), background);
write(join(res, "drawable/ic_launcher_foreground.xml"), foreground);
write(join(res, "drawable/ic_launcher_monochrome.xml"), monochrome);
write(join(res, "mipmap-anydpi-v26/ic_launcher.xml"), adaptive);
write(join(res, "mipmap-anydpi-v26/ic_launcher_round.xml"), adaptive);

// ---------- PNGs (legacy launchers on Android 7.x, store icon, preview) ----------
function svg(size, shape) {
  // Same artwork in a 108-unit space; legacy icons use the full square minus a
  // small margin, so the word can be a little larger than in the adaptive mask.
  const word = 74;
  const g = placed(gowa, word, 54, 54);
  const y = placed(yy, word, 54, 54);
  const clip = shape === "round" ? `<circle cx="54" cy="54" r="50"/>` : shape === "square" ? `<rect width="108" height="108"/>` : `<rect x="4" y="4" width="100" height="100" rx="24"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 108 108">
  <defs>
    <linearGradient id="bg" x1="12" y1="0" x2="96" y2="108" gradientUnits="userSpaceOnUse">${BG.map(([o, c]) => `<stop offset="${o}" stop-color="${c}"/>`).join("")}</linearGradient>
    <radialGradient id="glow" cx="88" cy="16" r="58" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#F5C2FF" stop-opacity=".4"/><stop offset="1" stop-color="#F5C2FF" stop-opacity="0"/></radialGradient>
    <radialGradient id="shade" cx="10" cy="104" r="62" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#2E1065" stop-opacity=".33"/><stop offset="1" stop-color="#2E1065" stop-opacity="0"/></radialGradient>
    <linearGradient id="yy" x1="0" y1="0" x2="1" y2="1">${YY.map(([o, c]) => `<stop offset="${o}" stop-color="${c}"/>`).join("")}</linearGradient>
    <clipPath id="c">${clip}</clipPath>
  </defs>
  <g clip-path="url(#c)">
    <rect width="108" height="108" fill="url(#bg)"/><rect width="108" height="108" fill="url(#glow)"/><rect width="108" height="108" fill="url(#shade)"/>
    <path d="${g}" fill="${INK}"/><path d="${y}" fill="url(#yy)"/>
  </g>
</svg>`;
}
const png = (size, shape, out) => sharp(Buffer.from(svg(size, shape))).png({ compressionLevel: 9 }).toFile(out);

const DPI = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const [d, px] of Object.entries(DPI)) {
  mkdirSync(join(res, `mipmap-${d}`), { recursive: true });
  await png(px, "rounded", join(res, `mipmap-${d}/ic_launcher.png`));
  await png(px, "round", join(res, `mipmap-${d}/ic_launcher_round.png`));
}
await png(512, "square", join(androidDir, "icon-512.png"));
console.log(`icons written · wordmark ${ww.toFixed(1)}×${wh.toFixed(1)} dp in the 66 dp safe circle`);
